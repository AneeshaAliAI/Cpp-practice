#include <iostream>
using namespace std;

int main()
{
    cout << "All Punctuators: " << endl;
    cout << endl;
    cout << "1. Punctuator: ; -  used to end a line"  << endl;
    cout << "2. Punctuator: , -  used to separate things"  << endl;
    cout << "3. Punctuator: { - used to start a block"  << endl;
    cout << "4. Punctuator: } - used to finish a block"  << endl;
    cout << "5. Punctuator: ( - used to start a bracket"  << endl;
    cout << "6. Punctuator: ) -  used to end a bracket" << endl;
    cout << "7. Punctuator: [ -  used to start an array"  << endl;
    cout << "8. Punctuator: ] - used to end an array"  << endl;
    cout << "9. Punctuator: # -  Preprocessor"  << endl;
    cout << "10. Punctuator: : -  Colon"  << endl;

    return 0;
}