#include <iostream>
using namespace std;

int main()
{
    // Single Line Comment - Compiler isko ignore karta hai
    cout << "Definition: Comment is a note for human, compiler ignores it." << endl;

    /* Multi Line Comment
       Ye 2 ya zyada lines ke liye hota hai
       Compiler isko bhi ignore karta hai */

    int a = 5; // a ki value 5 hai

    cout << "a = " << a << endl;

    return 0;
}