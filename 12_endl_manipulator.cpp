#include <iostream>
using namespace std;

int main()
{
    cout << "Definition: endl is a manipulator used to move cursor to new line and flush the output buffer." << endl;
    cout << "--------------------------------" << endl;

    cout << "Hello" << endl;
    cout << "Aneesha" << endl;
    cout << "Welcome" << endl;

    cout << "--------------------------------" << endl;
    cout << "Difference:" << endl;
    cout << "endl = new line + flush" << endl;
    cout << "\\n = only new line" << endl;

    return 0;
}